#include "ft_printf.h"

void	ft_putnbr(long n, int *count)
{
	if (n < 0)
	{
		n = -n;
		ft_putchar('-', count);
	}
	if (n > 9)
		ft_putnbr(n / 10, count);
	ft_putchar(n % 10 + '0', count);
}
